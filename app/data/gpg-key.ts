export const getKeyPreview = (key: string) => {
	const lines = key.split('\n')
	const header = lines[0]
	const footer = lines[lines.length - 1]
	const preview = lines.slice(1, 5).join('\n')
	return `${header}\n${preview}\n...\n${footer}`
}

